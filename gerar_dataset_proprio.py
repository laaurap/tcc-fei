def main():
    random.seed(42)
    linhas = []
    for cat, frases in POSITIVOS.items():
        linhas += [(f, 1, cat) for f in frases]
    for cat, frases in NEGATIVOS.items():
        linhas += [(f, 0, cat) for f in frases]
    random.shuffle(linhas)

    caminho = "dataset/violencia_psicologica_proprio.csv"
    with open(caminho, "w", encoding="utf-8-sig", newline="") as arq:
        w = csv.writer(arq)
        w.writerow(["texto", "rotulo", "categoria"])
        w.writerows(linhas)

    pos = sum(1 for _, r, _ in linhas if r == 1)
    print(f"{len(linhas)} frases ({pos} positivas, {len(linhas) - pos} negativas) -> {caminho}")


if __name__ == "__main__":
    main()
